from typing import List  # 引入类型注解 List，仅用于函数签名标注，不影响运行


class Solution:
    def secondGreaterElement(self, nums: List[int]) -> List[int]:
        # nums：输入数组；返回值 answer[i] 是 nums[i] 的"第二个更大值"

        n = len(nums)                 # 数组长度，后面用来初始化答案数组
        ans = [-1] * n                # 答案数组，先全部填 -1（默认"找不到"就是 -1）

        s1 = []                       # 栈1：存"还在等第一个更大值"的下标
        #                               不变量：栈内下标对应的 nums 值从栈底到栈顶单调递减

        s2 = []                       # 栈2：存"已找到第一个更大值、正在等第二个更大值"的下标
        #                               不变量：同样从栈底到栈顶单调递减

        # 从左到右遍历每个元素，i 是下标，x 是值 nums[i]
        for i, x in enumerate(nums):

            # ===== 第一步：处理 s2 —— x 可能是 s2 里某些元素的"第二个更大值" =====
            # 只要 s2 非空，且栈顶元素的值 < 当前值 x，
            # 说明 x 就是该栈顶元素遇到的第二个更大值（因为它已找到过第一个更大值）
            while s2 and nums[s2[-1]] < x:
                ans[s2[-1]] = x       # 记录答案：栈顶那个下标的第二个更大值就是 x
                s2.pop()              # 它已经"毕业"了，弹出，不再参与后续比较

            # ===== 第二步：处理 s1 —— x 是 s1 里某些元素的"第一个更大值" =====
            # 找出 s1 中从栈顶往下、所有值 < x 的那一段的起始位置 j。
            # 因为 s1 单调递减（栈顶最小），一旦遇到 >= x 的就可以停。
            j = len(s1)               # j 初始指向 s1 末尾之后（即先假设没有要搬的）
            while j and nums[s1[j - 1]] < x:
                j -= 1                # 栈顶方向逐个回退，直到 s1[j-1] 的值不再小于 x

            # s1[j:] 就是"第一个更大值 == x"的那批下标，需要从 s1 搬到 s2。
            # 直接按原顺序追加：s1[j:] 本身值递减，且都 < x，而 s2 里剩下的值都 >= x，
            # 所以追加后 s2 整体仍保持单调递减（这一点是不反转的关键）。
            s2 += s1[j:]              # 把这批下标搬进 s2，等待各自的第二个更大值
            del s1[j:]                # 从 s1 中删掉已搬走的这一段

            s1.append(i)             # 当前下标 i 入栈1，等待它自己的第一个更大值

        return ans                    # 遍历结束，ans 即为最终答案


