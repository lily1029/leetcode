if __name__ == "__main__":
    sol = Solution()
    print(sol.secondGreaterElement([2, 4, 0, 9, 6]))  # 期望 [9, 6, 6, -1, -1]
    print(sol.secondGreaterElement([3, 3]))           # 期望 [-1, -1]